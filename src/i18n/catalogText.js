/** Presentation-only translation for known product copy; persisted/API values stay untouched. */
export function translateCatalogText(value, language = 'es') {
  if (typeof value !== 'string' || language !== 'en') return value;
  const exact = exactTranslations.get(value.trim().toLocaleLowerCase('es'));
  if (exact) return exact;
  return replacements.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), value);
}
